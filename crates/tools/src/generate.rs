use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, anyhow, bail};

/// The sorted stems of every `<name>.svg` in `svg_dir`.
fn svg_names(svg_dir: &Path) -> Result<BTreeSet<String>> {
    if !svg_dir.is_dir() {
        bail!("SVG directory does not exist: {}", svg_dir.display());
    }

    // BTreeSet keeps the output sorted and de-duplicated.
    let mut names: BTreeSet<String> = BTreeSet::new();

    for entry in fs::read_dir(svg_dir)
        .with_context(|| anyhow!("Reading SVG directory {}", svg_dir.display()))?
    {
        let entry = entry?;
        let name = entry.file_name();

        let Some(name) = name.to_str() else {
            continue;
        };

        if let Some(stem) = name.strip_suffix(".svg") {
            names.insert(stem.to_owned());
        }
    }

    if names.is_empty() {
        bail!("No SVGs found in {}", svg_dir.display());
    }

    Ok(names)
}

/// Generate a Sass partial exposing a `$names` list built from every `<name>.svg` in
/// `svg_dir`. Names are sorted for deterministic output so regeneration produces no diff
/// when the set is unchanged. A hand-written partial iterates the list to build the
/// per-name rules (e.g. `_flags.scss`, `_icons.scss`).
pub fn svg_names_scss(svg_dir: &Path, with_uppercase: bool) -> Result<String> {
    let names = svg_names(svg_dir)?;

    let mut out = String::new();
    writeln!(
        out,
        "// @generated by `cargo run -p tools`; do not edit by hand."
    )?;
    writeln!(out)?;
    writeln!(out, "$names: (")?;

    for name in &names {
        if with_uppercase {
            writeln!(out, "    ('{}', '{name}'),", name.to_uppercase())?;
        } else {
            writeln!(out, "    '{name}',")?;
        }
    }

    writeln!(out, ");")?;
    Ok(out)
}

/// Generate the frontend's `flags` module: the uppercase ISO 3166-1 alpha-2 codes
/// that have a flag SVG in `flags_dir`, and `has_flag` to look one up.
pub fn flags_module(flags_dir: &Path) -> Result<String> {
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by `cargo run -p tools`; do not edit by hand."
    )?;
    writeln!(out)?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "const FLAGS: &[&str] = &[")?;

    for name in svg_names(flags_dir)? {
        if name.len() == 2 {
            writeln!(out, "    {:?},", name.to_uppercase())?;
        }
    }

    writeln!(out, "];")?;
    writeln!(out)?;
    writeln!(
        out,
        "/// Whether a flag is vendored for the uppercase ISO 3166-1 alpha-2 `code`."
    )?;
    writeln!(out, "pub(crate) fn has_flag(code: &str) -> bool {{")?;
    writeln!(out, "    FLAGS.binary_search(&code).is_ok()")?;
    writeln!(out, "}}")?;
    Ok(out)
}
